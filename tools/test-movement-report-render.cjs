const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const Vue = require('vue');
const compiler = require('vue-template-compiler');
const source = fs.readFileSync('src/views/reportes/ReporteRegMovimiento.vue', 'utf8');
const parsed = compiler.parseComponent(source);
const sandbox = { config: { API: '/api/' }, component: null };
vm.runInNewContext(parsed.script.content.replace(/import config[^;]+;/, '').replace('export default', 'component ='), sandbox);
const compiled = compiler.compileToFunctions(parsed.template.content);
const errors = [];
Vue.config.errorHandler = error => errors.push(error);
Vue.config.silent = true;
const report = new Vue(Object.assign({}, sandbox.component, compiled));
report._render();
assert.strictEqual(errors.length, 0, errors.map(error => error.message).join('; '));
assert.strictEqual(report.auditoriaFiltrada.length, 0);
report.auditoria = [{ Usuario: 'SUPERADMIN', Motivo: 'CORRECCION' }, { Usuario: 'OTRO', Motivo: 'ELIMINACION' }];
report.historialFiltro = 'superadmin';
assert.strictEqual(report.auditoriaFiltrada.length, 1);
report._render();
assert.strictEqual(errors.length, 0);
assert.strictEqual(report.activarBotones, true);
report.lstReporte = [{}];
assert.strictEqual(report.activarBotones, false);
console.log('Report initial render, audit filter and export availability passed.');
