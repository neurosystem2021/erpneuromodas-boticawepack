const assert = require('assert');
const { periodDays, rankedProducts, minimumProducts, calculate } = require('./load-source-module')('src/utils/replenishment.js');
assert.strictEqual(periodDays('2026-10-01', '2026-10-10'), 10);
assert.strictEqual(periodDays('2024-02-28', '2024-03-01'), 3);
['2026-02-30', '2026-99-01', ''].forEach(date => assert.throws(() => periodDays(date, '2026-10-10')));
assert.throws(() => periodDays('2026-10-11', '2026-10-10'));
const product = { IdProducto: 1, ControlaStock: 1, CantidadVentas: 30, ControlaStockMinimo: 1, StockMinimo: 10, stock: 999 };
const result = calculate(product, 5, 30, 14, 1);
assert.strictEqual(result.target, 24);
assert.strictEqual(result.suggested, 19);
assert.strictEqual(result.state, 'minimum');
assert.strictEqual(result.current, 5); // Historical balance must never override current stock.
assert.strictEqual(calculate(product, undefined, 30, 14, 1).state, 'unknown');
assert.strictEqual(calculate(product, undefined, 30, 14, 1).suggested, null);
assert.strictEqual(calculate(product, -2, 30, 14, 1).suggested, 26);
assert.strictEqual(calculate(product, 0, 30, 14, 1).state, 'urgent');
assert.strictEqual(calculate(product, 50, 30, 14, 1).suggested, 0);
assert.strictEqual(calculate(product, 10, 30, 5, 1).state, 'minimum');
assert.strictEqual(calculate({ ...product, ControlaStockMinimo: 0 }, 50, 30, 14, 1).state, 'configure');
assert.deepStrictEqual(rankedProducts([product, { ...product, IdProducto: 2, CantidadVentas: 60 }, { ...product, IdProducto: 3, Anulado: 1 }, { ...product, IdProducto: 4, ControlaStock: 0 }]).map(p => p.IdProducto), [2, 1]);
const noSales = { ...product, CantidadVentas: 0 };
assert.strictEqual(rankedProducts([noSales]).length, 0);
assert.strictEqual(minimumProducts([noSales]).length, 1);
assert.strictEqual(minimumProducts([{ ...noSales, ControlaStockMinimo: 0 }]).length, 0);
assert.strictEqual(minimumProducts([{ ...noSales, Anulado: 1 }]).length, 0);
assert.deepStrictEqual(rankedProducts([noSales, product]).map(item => item.IdProducto), [1]);
const atMinimum = calculate(noSales, 10, 30, 14, 1);
assert.strictEqual(atMinimum.state, 'minimum');
assert.strictEqual(atMinimum.suggested, 1);
assert.strictEqual(atMinimum.coverage, null);
assert.strictEqual(calculate(product, 15, 30, 14, 1).state, 'reorder');
console.log('Replenishment calculations passed.');
process.exit(0);
