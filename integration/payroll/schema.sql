CREATE TABLE IF NOT EXISTS Rhu_PlanillaPersonal (
 IdEmpleado INT PRIMARY KEY, Cargo VARCHAR(100) NOT NULL DEFAULT '', IdAlmacen INT NOT NULL DEFAULT 0,
 Sueldo DECIMAL(12,2) NOT NULL DEFAULT 0, Regimen VARCHAR(20) NOT NULL DEFAULT 'GENERAL', Pension VARCHAR(10) NOT NULL DEFAULT 'NINGUNO',
 AFP VARCHAR(40) NOT NULL DEFAULT '', TasaAFP DECIMAL(6,3) NOT NULL DEFAULT 0, FechaIngreso DATE NULL,
 DatosLaborales LONGTEXT NULL, DiaPago TINYINT UNSIGNED NULL, Banco VARCHAR(80) NOT NULL DEFAULT '', NumeroCuenta VARCHAR(80) NOT NULL DEFAULT '', CCI VARCHAR(20) NOT NULL DEFAULT '', Titular VARCHAR(150) NOT NULL DEFAULT '',
 Activo TINYINT NOT NULL DEFAULT 1, UsuarioReg VARCHAR(255), FechaMod DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Rhu_PlanillaPeriodo (
 IdPlanilla INT PRIMARY KEY AUTO_INCREMENT, IdEmpleado INT NOT NULL, Periodo CHAR(7) NOT NULL,
 Detalle LONGTEXT NOT NULL, Neto DECIMAL(12,2) NOT NULL, UsuarioReg VARCHAR(255) NOT NULL, FechaReg DATETIME NOT NULL,
 UNIQUE KEY empleado_periodo(IdEmpleado,Periodo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Rhu_PlanillaPago (
 IdPago INT PRIMARY KEY AUTO_INCREMENT, IdPlanilla INT NULL, IdCliente INT NULL, Tipo VARCHAR(25) NOT NULL,
 Importe DECIMAL(12,2) NOT NULL, IdCuenta INT NOT NULL, IdCajaBanco INT NOT NULL, Fecha DATE NOT NULL,
 Referencia VARCHAR(150) NOT NULL DEFAULT '', UsuarioReg VARCHAR(255) NOT NULL, FechaReg DATETIME NOT NULL,
 DatosDestino LONGTEXT NULL, Token VARCHAR(80) NOT NULL, Anulado TINYINT NOT NULL DEFAULT 0, UsuarioAnula VARCHAR(255) NULL,
 UNIQUE KEY payment_token(Token), KEY periodo(IdPlanilla), KEY cliente(IdCliente)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Rhu_ComisionAplicacion (
 IdPago INT NOT NULL, IdDocVenta INT NOT NULL, Importe DECIMAL(12,2) NOT NULL,
 PRIMARY KEY(IdPago,IdDocVenta)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
