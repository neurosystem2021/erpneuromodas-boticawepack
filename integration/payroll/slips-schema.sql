CREATE TABLE IF NOT EXISTS Rhu_PlanillaBoleta (
IdBoleta INT PRIMARY KEY AUTO_INCREMENT, IdPlanilla INT NOT NULL, Version INT NOT NULL,
Datos LONGTEXT NOT NULL, HashDocumento CHAR(64) NOT NULL, UsuarioReg VARCHAR(255) NOT NULL, FechaReg DATETIME NOT NULL,
UNIQUE KEY planilla_version(IdPlanilla,Version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
