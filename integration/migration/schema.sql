CREATE TABLE IF NOT EXISTS Mig_Run (
 id VARCHAR(40) PRIMARY KEY, owner VARCHAR(100) NOT NULL, source_hash VARCHAR(64) NOT NULL,
 plan_hash VARCHAR(64) NOT NULL, status VARCHAR(24) NOT NULL, cursor_pos INTEGER NOT NULL DEFAULT 0,
 total_rows INTEGER NOT NULL, plan_json LONGTEXT NOT NULL, created_at VARCHAR(30) NOT NULL,
 approved_by VARCHAR(100) NULL, approved_at VARCHAR(30) NULL, last_error VARCHAR(100) NULL,
 UNIQUE KEY migration_plan(source_hash,plan_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Mig_PlanRow (
 run_id VARCHAR(40) NOT NULL, ordinal_pos INTEGER NOT NULL, entry_json MEDIUMTEXT NOT NULL,
 PRIMARY KEY(run_id,ordinal_pos), FOREIGN KEY(run_id) REFERENCES Mig_Run(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Mig_Record (
 id VARCHAR(64) PRIMARY KEY, run_id VARCHAR(40) NOT NULL, entity VARCHAR(100) NOT NULL,
 source_key VARCHAR(255) NOT NULL, original_json MEDIUMTEXT NOT NULL, mapped_json MEDIUMTEXT NOT NULL,
 row_hash VARCHAR(64) NOT NULL, FOREIGN KEY(run_id) REFERENCES Mig_Run(id),
 UNIQUE KEY migration_origin(run_id,entity,source_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Mig_IdMap (
 run_id VARCHAR(40) NOT NULL, entity VARCHAR(100) NOT NULL, old_key VARCHAR(255) NOT NULL,
 new_id VARCHAR(64) NOT NULL, links_json MEDIUMTEXT NOT NULL,
 PRIMARY KEY(run_id,entity,old_key), FOREIGN KEY(new_id) REFERENCES Mig_Record(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Mig_Batch (
 run_id VARCHAR(40) NOT NULL, start_pos INTEGER NOT NULL, end_pos INTEGER NOT NULL,
 row_count INTEGER NOT NULL, completed_at VARCHAR(30) NOT NULL,
 PRIMARY KEY(run_id,start_pos), FOREIGN KEY(run_id) REFERENCES Mig_Run(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Mig_Issue (
 run_id VARCHAR(40) NOT NULL, code VARCHAR(64) NOT NULL, severity VARCHAR(12) NOT NULL,
 detail_json MEDIUMTEXT NOT NULL, justification TEXT NULL, resolved_by VARCHAR(100) NULL,
 PRIMARY KEY(run_id,code), FOREIGN KEY(run_id) REFERENCES Mig_Run(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Mig_Event (
 id VARCHAR(40) PRIMARY KEY, run_id VARCHAR(40) NOT NULL, actor VARCHAR(100) NOT NULL,
 action VARCHAR(40) NOT NULL, data_json MEDIUMTEXT NOT NULL, created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY(run_id) REFERENCES Mig_Run(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
