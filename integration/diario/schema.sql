CREATE TABLE IF NOT EXISTS Rhu_DiarioVinculo (
 IdEmpleado INT NOT NULL PRIMARY KEY, Usuario VARCHAR(255) NOT NULL,
 UNIQUE KEY usuario (Usuario)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Rhu_DiarioTarea (
 Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 Usuario VARCHAR(255) NULL, IdEmpleado INT NULL,
 Titulo VARCHAR(180) NOT NULL, Indicaciones TEXT NOT NULL,
 Inicio DATETIME NOT NULL, Fin DATETIME NOT NULL,
 Estado VARCHAR(20) NOT NULL DEFAULT 'pendiente', Prioridad VARCHAR(10) NOT NULL DEFAULT 'normal',
 Anticipacion INT NOT NULL DEFAULT 15, Frecuencia INT NOT NULL DEFAULT 15,
 Repeticion VARCHAR(10) NOT NULL DEFAULT 'ninguna',
 Segundos INT NOT NULL DEFAULT 0, EnCursoDesde DATETIME NULL,
 InicioReal DATETIME NULL, FinReal DATETIME NULL,
 Creador VARCHAR(255) NOT NULL, Creada DATETIME NOT NULL, Modificada DATETIME NOT NULL,
 Version INT NOT NULL DEFAULT 1, Anterior INT NULL,
 Archivada TINYINT NOT NULL DEFAULT 0, ArchivadaPor VARCHAR(255) NULL, ArchivadaFecha DATETIME NULL,
 Objetivo DECIMAL(12,2) NOT NULL DEFAULT 0, Realizado DECIMAL(12,2) NOT NULL DEFAULT 0,
 Unidad VARCHAR(60) NOT NULL DEFAULT '', Puntos INT NOT NULL DEFAULT 1,
 Resultado TEXT NULL, Evidencia VARCHAR(1000) NOT NULL DEFAULT '',
 Calidad TINYINT NULL, Evaluador VARCHAR(255) NULL, FechaEvaluacion DATETIME NULL,
 Reconocimiento TEXT NULL,
 UNIQUE KEY siguiente (Anterior), KEY usuario_fecha (Usuario,Inicio),
 KEY empleado_fecha (IdEmpleado,Inicio), KEY estado_fin (Estado,Fin)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Rhu_DiarioPersonal (
 Id INT AUTO_INCREMENT PRIMARY KEY, Usuario VARCHAR(255) NOT NULL,
 Titulo VARCHAR(180) NOT NULL, Detalle TEXT NOT NULL, Fecha DATETIME NOT NULL,
 Anticipacion INT NOT NULL DEFAULT 15, Frecuencia INT NOT NULL DEFAULT 15,
 Repeticion VARCHAR(10) NOT NULL DEFAULT 'ninguna', Estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
 Recordar TINYINT(1) NOT NULL DEFAULT 1,
 Version INT NOT NULL DEFAULT 1, Anterior INT NULL, UNIQUE KEY siguiente (Anterior),
 KEY usuario_fecha (Usuario,Fecha)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Rhu_DiarioEvento (
 Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, Tarea INT NOT NULL,
 Usuario VARCHAR(255) NOT NULL, Accion VARCHAR(30) NOT NULL,
 Texto TEXT NOT NULL, Fecha DATETIME NOT NULL,
 KEY tarea (Tarea,Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
