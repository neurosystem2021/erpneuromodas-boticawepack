CREATE TABLE IF NOT EXISTS Co_SchemaVersion (Version VARCHAR(80) PRIMARY KEY, Checksum CHAR(64) NOT NULL, AppliedAt DATETIME NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Co_Company (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, Name VARCHAR(200) NOT NULL, Ruc CHAR(11) NOT NULL UNIQUE,
 Currency CHAR(3) NOT NULL DEFAULT 'PEN', Regime VARCHAR(30) NOT NULL, Obligation VARCHAR(12) NOT NULL DEFAULT 'none',
 Config LONGTEXT NOT NULL, Active TINYINT NOT NULL DEFAULT 1, Version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Member (
 CompanyId BIGINT UNSIGNED NOT NULL, Username VARCHAR(100) NOT NULL, Role VARCHAR(20) NOT NULL,
 PRIMARY KEY(CompanyId,Username), FOREIGN KEY(CompanyId) REFERENCES Co_Company(Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Branch (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, Name VARCHAR(160) NOT NULL,
 WarehouseId BIGINT UNSIGNED NULL UNIQUE, UNIQUE KEY(CompanyId,Id), FOREIGN KEY(CompanyId) REFERENCES Co_Company(Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Account (
 CompanyId BIGINT UNSIGNED NOT NULL, Code VARCHAR(20) NOT NULL, Name VARCHAR(200) NOT NULL, ParentCode VARCHAR(20) NULL,
 Nature VARCHAR(8) NOT NULL, Class VARCHAR(20) NOT NULL, ReportGroup VARCHAR(60) NOT NULL,
 Postable TINYINT NOT NULL DEFAULT 1, Active TINYINT NOT NULL DEFAULT 1,
 PRIMARY KEY(CompanyId,Code), FOREIGN KEY(CompanyId) REFERENCES Co_Company(Id),
 FOREIGN KEY(CompanyId,ParentCode) REFERENCES Co_Account(CompanyId,Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Period (
 CompanyId BIGINT UNSIGNED NOT NULL, Period CHAR(7) NOT NULL, State VARCHAR(12) NOT NULL DEFAULT 'open',
 NextNumber BIGINT UNSIGNED NOT NULL DEFAULT 1, ClosedBy VARCHAR(100) NULL, ClosedAt DATETIME NULL,
 PRIMARY KEY(CompanyId,Period), FOREIGN KEY(CompanyId) REFERENCES Co_Company(Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Entry (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, BranchId BIGINT UNSIGNED NULL,
 Period CHAR(7) NOT NULL, EntryDate DATE NOT NULL, Number BIGINT UNSIGNED NULL, Currency CHAR(3) NOT NULL,
 ExchangeRate DECIMAL(18,8) NOT NULL, Memo VARCHAR(500) NOT NULL, Status VARCHAR(16) NOT NULL DEFAULT 'draft',
 SourceType VARCHAR(30) NOT NULL, SourceId VARCHAR(100) NOT NULL, SourceHash CHAR(64) NOT NULL,
 Document VARCHAR(100) NOT NULL DEFAULT '', ElectronicData LONGTEXT NULL, ReversalOf BIGINT UNSIGNED NULL, Version INT NOT NULL DEFAULT 1,
 CreatedBy VARCHAR(100) NOT NULL, CreatedAt DATETIME NOT NULL, ReviewedBy VARCHAR(100) NULL,
 ApprovedBy VARCHAR(100) NULL, PostedBy VARCHAR(100) NULL, PostedAt DATETIME NULL,
 KEY(CompanyId,Status,EntryDate,BranchId), UNIQUE KEY(CompanyId,SourceType,SourceId), UNIQUE KEY(CompanyId,Period,Number), UNIQUE KEY(CompanyId,Id),
 UNIQUE KEY(ReversalOf), FOREIGN KEY(CompanyId,Period) REFERENCES Co_Period(CompanyId,Period),
 FOREIGN KEY(CompanyId,BranchId) REFERENCES Co_Branch(CompanyId,Id), FOREIGN KEY(ReversalOf) REFERENCES Co_Entry(Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Line (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, EntryId BIGINT UNSIGNED NOT NULL,
 Account VARCHAR(20) NOT NULL, Debit BIGINT NOT NULL DEFAULT 0, Credit BIGINT NOT NULL DEFAULT 0,
 OriginalDebit BIGINT NOT NULL DEFAULT 0, OriginalCredit BIGINT NOT NULL DEFAULT 0,
 PartyType VARCHAR(15) NOT NULL DEFAULT '', PartyId VARCHAR(40) NOT NULL DEFAULT '',
 CashFlow VARCHAR(15) NOT NULL DEFAULT '', Memo VARCHAR(500) NOT NULL DEFAULT '',
 UNIQUE KEY(CompanyId,Id), KEY(CompanyId,Account),
 FOREIGN KEY(CompanyId,EntryId) REFERENCES Co_Entry(CompanyId,Id), FOREIGN KEY(CompanyId,Account) REFERENCES Co_Account(CompanyId,Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Audit (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, Username VARCHAR(100) NOT NULL,
 Action VARCHAR(40) NOT NULL, Entity VARCHAR(30) NOT NULL, EntityId VARCHAR(100) NOT NULL, Data LONGTEXT NOT NULL,
 CreatedAt DATETIME NOT NULL, FOREIGN KEY(CompanyId) REFERENCES Co_Company(Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Source (
 CompanyId BIGINT UNSIGNED NOT NULL, Kind VARCHAR(30) NOT NULL, SourceId VARCHAR(100) NOT NULL,
 SourceHash CHAR(64) NOT NULL, Snapshot LONGTEXT NOT NULL, State VARCHAR(16) NOT NULL DEFAULT 'pending', Revision INT NOT NULL DEFAULT 1,
 Reason VARCHAR(500) NOT NULL DEFAULT '', EntryId BIGINT UNSIGNED NULL, CapturedAt DATETIME NOT NULL,
 PRIMARY KEY(CompanyId,Kind,SourceId), UNIQUE KEY(CompanyId,EntryId), FOREIGN KEY(CompanyId,EntryId) REFERENCES Co_Entry(CompanyId,Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_TaxDocument (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, EntryId BIGINT UNSIGNED NOT NULL,
 Kind VARCHAR(10) NOT NULL, IssueDate DATE NOT NULL, TaxPeriod CHAR(7) NOT NULL, DocType CHAR(2) NOT NULL,
 Series VARCHAR(20) NOT NULL, DocNumber VARCHAR(30) NOT NULL, PartyDocType VARCHAR(2) NOT NULL,
 PartyDoc VARCHAR(20) NOT NULL, PartyName VARCHAR(200) NOT NULL, Taxable BIGINT NOT NULL DEFAULT 0,
 Exempt BIGINT NOT NULL DEFAULT 0, Unaffected BIGINT NOT NULL DEFAULT 0, FreeAmount BIGINT NOT NULL DEFAULT 0, FreeIgv BIGINT NOT NULL DEFAULT 0,
 Igv BIGINT NOT NULL DEFAULT 0, OtherTaxes BIGINT NOT NULL DEFAULT 0, Total BIGINT NOT NULL,
 Withholding BIGINT NOT NULL DEFAULT 0, Perception BIGINT NOT NULL DEFAULT 0, Detraction BIGINT NOT NULL DEFAULT 0,
 CreditEligible TINYINT NOT NULL DEFAULT 0, ReferenceDoc VARCHAR(100) NOT NULL DEFAULT '', Sign SMALLINT NOT NULL DEFAULT 1, OriginalData LONGTEXT NOT NULL,
 State VARCHAR(12) NOT NULL DEFAULT 'active', VoidReason VARCHAR(500) NULL, VoidBy VARCHAR(100) NULL, VoidAt DATETIME NULL,
 UNIQUE KEY(CompanyId,EntryId), FOREIGN KEY(CompanyId,TaxPeriod) REFERENCES Co_Period(CompanyId,Period), FOREIGN KEY(CompanyId,EntryId) REFERENCES Co_Entry(CompanyId,Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Bank (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, Name VARCHAR(120) NOT NULL,
 Number VARCHAR(80) NOT NULL, Currency CHAR(3) NOT NULL, Account VARCHAR(20) NOT NULL, LegacyId BIGINT NULL,
 UNIQUE KEY(CompanyId,Id), UNIQUE KEY(CompanyId,Number), UNIQUE KEY(LegacyId), FOREIGN KEY(CompanyId,Account) REFERENCES Co_Account(CompanyId,Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_BankItem (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, BankId BIGINT UNSIGNED NOT NULL,
 ExternalId VARCHAR(120) NOT NULL, ItemDate DATE NOT NULL, Memo VARCHAR(500) NOT NULL,
 Amount BIGINT NOT NULL, Hash CHAR(64) NOT NULL, UNIQUE KEY(CompanyId,BankId,ExternalId), UNIQUE KEY(CompanyId,Id),
 FOREIGN KEY(CompanyId,BankId) REFERENCES Co_Bank(CompanyId,Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_BankMatch (
 CompanyId BIGINT UNSIGNED NOT NULL, BankItemId BIGINT UNSIGNED NOT NULL, LineId BIGINT UNSIGNED NOT NULL,
 Amount BIGINT NOT NULL, Username VARCHAR(100) NOT NULL, CreatedAt DATETIME NOT NULL, PRIMARY KEY(CompanyId,BankItemId,LineId), KEY(CompanyId,LineId),
 FOREIGN KEY(CompanyId,BankItemId) REFERENCES Co_BankItem(CompanyId,Id), FOREIGN KEY(CompanyId,LineId) REFERENCES Co_Line(CompanyId,Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_BankStatement (
 CompanyId BIGINT UNSIGNED NOT NULL, BankId BIGINT UNSIGNED NOT NULL, DateFrom DATE NOT NULL, DateTo DATE NOT NULL,
 Opening BIGINT NOT NULL, Closing BIGINT NOT NULL, Reference VARCHAR(200) NOT NULL, Version INT NOT NULL DEFAULT 1,
 PRIMARY KEY(CompanyId,BankId,DateFrom,DateTo), FOREIGN KEY(CompanyId,BankId) REFERENCES Co_Bank(CompanyId,Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_Asset (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, CompanyId BIGINT UNSIGNED NOT NULL, BranchId BIGINT UNSIGNED NULL,
 Name VARCHAR(160) NOT NULL, StartDate DATE NOT NULL, Cost BIGINT NOT NULL, Residual BIGINT NOT NULL,
 LifeMonths INT NOT NULL, ExpenseAccount VARCHAR(20) NOT NULL, AccumulatedAccount VARCHAR(20) NOT NULL,
 UNIQUE KEY(CompanyId,Id), FOREIGN KEY(CompanyId,BranchId) REFERENCES Co_Branch(CompanyId,Id),
 FOREIGN KEY(CompanyId,ExpenseAccount) REFERENCES Co_Account(CompanyId,Code),
 FOREIGN KEY(CompanyId,AccumulatedAccount) REFERENCES Co_Account(CompanyId,Code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Co_ExternalRegister (
 CompanyId BIGINT UNSIGNED NOT NULL, Period CHAR(7) NOT NULL, Kind VARCHAR(10) NOT NULL,
 DocumentKey VARCHAR(150) NOT NULL, Total BIGINT NOT NULL, Igv BIGINT NOT NULL, Payload LONGTEXT NOT NULL,
 PRIMARY KEY(CompanyId,Period,Kind,DocumentKey), FOREIGN KEY(CompanyId) REFERENCES Co_Company(Id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
